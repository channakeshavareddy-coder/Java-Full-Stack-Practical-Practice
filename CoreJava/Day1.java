public class Day1{
    public static void main(String[]args){
        System.out.println("Hello, World!");
    }
}

/*
 - public: makes the main method accessible from outside its class.
 - static: allows the main method to be called without creating an object of the class.
 - void: indicates that the main method does not return any value.
 - main: is the method name that the JVM recognizes as the entry point of a Java application.
 - String[] args: is an array of strings used to receive command-line arguments passed to the program.
 */